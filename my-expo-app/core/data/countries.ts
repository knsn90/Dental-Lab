const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

type Lang = 'tr' | 'en' | 'de' | 'fa';
const langOf = (l: string | null | undefined): Lang => (l === 'en' || l === 'de' || l === 'fa' ? l : 'tr');

export function isCountryCode(code: string | null | undefined): boolean {
  return BY_CODE.has(String(code ?? '').toUpperCase());
}

/** Kod → seçili dilde ad (bilinmiyorsa kodun kendisi). */
export function countryName(code: string | null | undefined, lang?: string | null): string {
  const c = BY_CODE.get(String(code ?? '').toUpperCase());
  return c ? c[langOf(lang)] : String(code ?? '');
}

/** Açılır liste: seçili dilde alfabetik adlar (Türkiye her zaman en üstte). */
export function countryOptions(lang?: string | null): Array<{ code: string; name: string }> {
  const L = langOf(lang);
  const rows = COUNTRIES.map((c) => ({ code: c.code, name: c[L] }));
  rows.sort((a, b) => (a.code === 'TR' ? -1 : b.code === 'TR' ? 1 : a.name.localeCompare(b.name, L)));
  return rows;
}

/** Seçili dildeki ad → kod (açılır listeden dönen ad için). */
export function countryCodeFromName(name: string, lang?: string | null): string | null {
  const L = langOf(lang);
  const n = name.trim().toLocaleLowerCase(L);
  const hit = COUNTRIES.find((c) => c[L].toLocaleLowerCase(L) === n);
  return hit?.code ?? null;
}
